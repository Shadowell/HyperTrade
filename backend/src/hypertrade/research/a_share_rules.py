@dataclass
class AShareValidationReport:
    """Report generated by AShareRuleValidator."""

    valid: bool
    violations: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    metrics: dict[str, Any] = field(default_factory=dict)


class AShareRuleValidator:
    """Validates signal arrays, positions and trade timelines against A-Share rules."""

    @classmethod
    def validate_signals_and_positions(
        cls,
        signals: Sequence[int | float],
        positions: Sequence[float | Decimal] | None = None,
    ) -> AShareValidationReport:
        """Validate that signals and positions satisfy the Long-Only spot rule."""
        violations: list[str] = []
        warnings: list[str] = []

        # Check signals
        for idx, sig in enumerate(signals):
            if sig < 0:
                violations.append(
                    f"A-Share Long-Only Violation: Signal at index {idx} has negative value {sig}. "
                    "Short selling (-1) is prohibited in China spot equities."
                )

        # Check positions
        if positions is not None:
            for idx, pos in enumerate(positions):
                pos_val = float(pos)
                if pos_val < 0.0:
                    violations.append(
                        f"A-Share Spot Violation: Position sizing at index {idx} "
                        f"is negative ({pos_val}). "
                        "Negative positions are illegal for spot accounts."
                    )
                elif pos_val > 1.0:
                    warnings.append(
                        f"Position sizing at index {idx} exceeds 1.0 ({pos_val}); "
                        "leverage is not permitted for standard spot trading."
                    )

        return AShareValidationReport(
            valid=len(violations) == 0,
            violations=violations,
            warnings=warnings,
            metrics={"total_bars": len(signals), "violation_count": len(violations)},
        )

    @classmethod
    def validate_t1_sequence(
        cls,
        timestamps: Sequence[datetime | date | str | int],
        signals: Sequence[int | float],
        *,
        signal_mode: str = "position",
    ) -> AShareValidationReport:
        """Validate T+1 compliance ensuring intraday buy-then-sell is not executed.

        Args:
            timestamps: Bar timestamps.
            signals: Signal sequence. If signal_mode="position", 1 indicates long and
                0 indicates flat (sell occurs only on 1 -> 0 transition).
                If signal_mode="action", 1 is buy, -1 is sell, and 0 is hold.
            signal_mode: "position" or "action".
        """
        if len(timestamps) != len(signals):
            return AShareValidationReport(
                valid=False,
                violations=["timestamps and signals length mismatch"],
            )

        violations: list[str] = []
        dates: list[date] = []
        for ts in timestamps:
            if isinstance(ts, datetime):
                dates.append(ts.date())
            elif isinstance(ts, date):
                dates.append(ts)
            elif isinstance(ts, str):
                try:
                    dt = datetime.fromisoformat(ts.replace("Z", "+00:00"))
                    dates.append(dt.date())
                except Exception:
                    dates.append(date.fromisoformat(ts[:10]))
            elif isinstance(ts, (int, float)):
                sec = ts / 1000.0 if ts > 1e11 else float(ts)
                dates.append(datetime.fromtimestamp(sec).date())
            else:
                violations.append(f"unsupported timestamp type: {type(ts)}")
                return AShareValidationReport(valid=False, violations=violations)

        available_shares = 0
        pending_shares = 0
        current_day: date | None = None
        prev_sig: float = 0.0

        for idx, (d, sig_raw) in enumerate(zip(dates, signals, strict=False)):
            sig = float(sig_raw)
            if current_day != d:
                # Settle yesterday's buys
                available_shares += pending_shares
                pending_shares = 0
                current_day = d

            is_buy = False
            is_sell = False

            if signal_mode == "position":
                if sig > 0 and prev_sig <= 0:
                    is_buy = True
                elif sig <= 0 and prev_sig > 0:
                    is_sell = True
            else:  # action mode
                if sig > 0:
                    is_buy = True
                elif sig < 0:
                    is_sell = True

            if is_buy:
                pending_shares += 1
            elif is_sell:
                if available_shares <= 0 and pending_shares > 0:
                    violations.append(
                        f"T+1 Settlement Violation at bar {idx} (date {d}): "
                        "Attempted to sell shares on the same day they were bought. "
                        "Available T+1 shares = 0."
                    )
                elif available_shares > 0:
                    available_shares -= 1

            prev_sig = sig

        return AShareValidationReport(
            valid=len(violations) == 0,
            violations=violations,
            metrics={"trade_days": len(set(dates)), "violation_count": len(violations)},
        )

    @classmethod
    def calculate_friction_costs(
        cls,
        *,
        buy_turnover: float,
        sell_turnover: float,
        slippage_bps: float = 1.5,
    ) -> dict[str, float]:
        """Compute complete institutional A-Share transaction friction breakdown in CNY."""
        rules = AShareMarketRules()

        # 1. Stamp Duty (印花税, 0.05% sell only)
        stamp_duty = sell_turnover * rules.stamp_duty_sell_only

        # 2. Transfer Fee (过户费, 0.001% both sides)
        transfer_fee = (buy_turnover + sell_turnover) * rules.transfer_fee_both_sides

        # 3. Handling Fee (经手费与证管费, ~0.00341% both sides)
        handling_fee = (buy_turnover + sell_turnover) * rules.handling_fee_both_sides

        # 4. Broker Commission (万2.5, min 5 CNY per side if non-zero)
        buy_comm = (
            max(rules.broker_commission_min_cny, buy_turnover * rules.broker_commission_rate)
            if buy_turnover > 0
            else 0.0
        )
        sell_comm = (
            max(rules.broker_commission_min_cny, sell_turnover * rules.broker_commission_rate)
            if sell_turnover > 0
            else 0.0
        )
        commission = buy_comm + sell_comm

        # 5. Slippage (e.g. 1.5 bps)
        slippage_rate = slippage_bps / 10000.0
        slippage_cost = (buy_turnover + sell_turnover) * slippage_rate

        total_friction = stamp_duty + transfer_fee + handling_fee + commission + slippage_cost

        return {
            "stamp_duty": round(stamp_duty, 2),
            "transfer_fee": round(transfer_fee, 2),
            "handling_fee": round(handling_fee, 2),
            "commission": round(commission, 2),
            "slippage_cost": round(slippage_cost, 2),
            "total_friction": round(total_friction, 2),
            "effective_friction_bps": (
                round((total_friction / (buy_turnover + sell_turnover)) * 10000.0, 2)
                if (buy_turnover + sell_turnover) > 0
                else 0.0
            ),
        }
