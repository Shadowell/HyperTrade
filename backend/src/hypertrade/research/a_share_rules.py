"""China A-Share Market Microstructure Hard Rules & Prompt Constraints.

Encodes institutional rules of China A-share equity trading into:
1. Standard Market Microstructure Rule Specifications (T+1, Long-Only, Price Limits, Tax/Fees).
2. LLM / Co-STEER Prompt Constraint Injector for Strategy Synthesis.
3. Static & Dynamic Runtime Rule Validator for Signals and Trade Sequences.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass, field
from datetime import date, datetime
from decimal import Decimal
from typing import Any


@dataclass(frozen=True)
class AShareMarketRules:
    """Institutional microstructure specifications for China A-Share markets."""

    t_plus_1_settlement: bool = True
    long_only_spot: bool = True
    allow_naked_short: bool = False

    # Price Limits (Daily limit up / limit down)
    price_limit_main_board: float = 0.10  # 00xxxx, 60xxxx (+/-10%)
    price_limit_chinext_star: float = 0.20  # 30xxxx, 68xxxx (+/-20%)
    price_limit_st: float = 0.05  # ST / *ST (+/-5%)
    price_limit_first_day: float = 0.00  # First day of IPO: unconstrained or special

    # Transaction Friction Costs
    stamp_duty_sell_only: float = 0.0005  # 0.05% (5‱) imposed on seller only
    transfer_fee_both_sides: float = 0.00001  # 0.01‰ (0.1‱) China Clear both sides
    handling_fee_both_sides: float = 0.0000341  # Exchange handling & regulation fee
    broker_commission_rate: float = 0.00025  # Standard万2.5
    broker_commission_min_cny: float = 5.0  # Minimum 5 CNY per trade
    standard_slippage_bps: float = 1.5  # 1.5 bps standard liquidity slippage


